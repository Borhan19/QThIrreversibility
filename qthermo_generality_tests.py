def select_local_defect_reference_time(
    N: int,
    Q: int,
    V1: float,
    V2: float,
    scout_dt: float = 0.15,
    tmax: float = 7.5,
):
    """
    Choose one fixed physical time for the local defect-rate refinement.

    The reference time is selected once from the original scout resolution as the
    time inside the primary 10%-90% window at which the finite-step V_pi is largest.
    The same physical t_ref is then held fixed while tau is reduced. This avoids
    confusing a changing time grid with genuine tau-scaling.
    """
    H, basis, _ = build_hardcore_1d_hamiltonian(N, Q, V1, V2)
    macro = hard_core_1d_macro_data(basis, N, Q, Kcells=4)
    init = hard_core_left_half_initial_indices(basis, N, Q)
    times = np.arange(0.0, tmax + 0.5 * scout_dt, scout_dt)

    traj = analyze_time_independent_class(
        H,
        macro,
        init,
        times,
        tau=scout_dt,
        compute_history_defect=False,
        metadata={"N": N, "Q": Q, "V1": V1, "V2": V2},
    )

    if traj.i10 is None or traj.i90 is None or traj.i90 <= traj.i10:
        raise RuntimeError("Could not identify the primary relaxation window.")

    local = traj.vpi[traj.i10 : traj.i90]
    rel_idx = int(np.argmax(local))
    idx = traj.i10 + rel_idx

    return {
        "t_ref": float(traj.times[idx]),
        "scout_vpi": float(traj.vpi[idx]),
        "sigma_ref": float(traj.sigma[idx]),
        "instantaneous_rate_ref": float(traj.rate[idx]),
        "t10": float(traj.times[traj.i10]),
        "t90": float(traj.times[traj.i90]),
    }


def evaluate_fixed_time_defect_scaling(
    N: int,
    Q: int,
    V1: float,
    V2: float,
    t_ref: float,
    tau_values: np.ndarray,
):
    """
    Evaluate V_pi(t_ref -> t_ref+tau) at one fixed physical time.

    We report both the absolute defect and the finite-step defect-rate proxy

        nu_pi(t_ref; tau) = V_pi(t_ref -> t_ref+tau) / tau.

    We also compute the finite-step entropy slope

        [S_R(t_ref+tau)-S_R(t_ref)] / tau

    and the exact instantaneous entropy rate dot S_R(t_ref). The latter is obtained
    directly from the Schrodinger equation, not by finite differences.
    """
    H, basis, _ = build_hardcore_1d_hamiltonian(N, Q, V1, V2)
    macro = hard_core_1d_macro_data(basis, N, Q, Kcells=4)
    init = hard_core_left_half_initial_indices(basis, N, Q)

    psi0 = basis_columns(len(basis), init)
    if abs(t_ref) < 1e-15:
        psi_t = psi0.copy()
    else:
        psi_t = expm_multiply(-1j * H * t_ref, psi0)

    p_t = macro_probabilities_from_columns(psi_t, macro)
    S_t = coarse_entropy(p_t, macro.omega)
    dp_t = macro_rate_from_columns(psi_t, H, macro)
    rate_t = entropy_rate_from_dp(p_t, dp_t, macro.omega)

    rows = []
    for tau in np.asarray(tau_values, dtype=float):
        psi_q = expm_multiply(-1j * H * tau, psi_t)
        p_q = macro_probabilities_from_columns(psi_q, macro)
        S_q = coarse_entropy(p_q, macro.omega)
        vpi = majorization_defect(p_t, p_q, macro.pi)
        margin = lorenz_margin(p_t, p_q, macro.pi)
        dS = S_q - S_t

        rows.append(
            {
                "tau": float(tau),
                "vpi": float(vpi),
                "nu_pi": float(vpi / tau),
                "lorenz_margin": float(margin),
                "dS": float(dS),
                "finite_entropy_rate": float(dS / tau),
                "instantaneous_entropy_rate": float(rate_t),
            }
        )

    return {
        "N": N,
        "Q": Q,
        "V1": V1,
        "V2": V2,
        "t_ref": float(t_ref),
        "p_ref": p_t,
        "S_ref": float(S_t),
        "instantaneous_entropy_rate": float(rate_t),
        "rows": rows,
    }


