def plot_local_defect_rate(data: dict):
    """
    Fixed-time local refinement of the stronger relative-majorization defect.

    Panel (a) shows the finite-step defect-rate proxy V_pi/tau. A nonzero limiting
    trend means the stronger local order can fail even though V_pi itself vanishes
    linearly as tau -> 0.

    Panel (b) compares the finite-step entropy slope with the exact instantaneous
    entropy rate at the same fixed physical time. Positive values demonstrate that
    failure of the stronger order need not imply entropy decrease.
    """
    colors = [RED, BLUE, GREEN]
    markers = ["o", "s", "^"]

    fig, axes = plt.subplots(1, 2, figsize=(6.8, 2.7))

    for color, marker, case in zip(colors, markers, data["cases"]):
        rows = sorted(case["rows"], key=lambda r: r["tau"])
        tau = np.array([r["tau"] for r in rows], dtype=float)
        nu = np.array([r["nu_pi"] for r in rows], dtype=float)
        slope = np.array([r["finite_entropy_rate"] for r in rows], dtype=float)
        rate0 = float(case["instantaneous_entropy_rate"])
        label = rf"$V_2/J={case['V2']:.1f}$"

        axes[0].semilogy(tau, np.maximum(nu, 1e-16), marker=marker, color=color, label=label)

        x_entropy = np.concatenate([[0.0], tau])
        y_entropy = np.concatenate([[rate0], slope])
        axes[1].plot(x_entropy, y_entropy, marker=marker, color=color, label=label)
        axes[1].scatter([0.0], [rate0], marker="*", s=42, color=color, zorder=5)

    axes[0].set_xlabel(r"$J\tau$")
    axes[0].set_ylabel(r"$\mathcal{V}_\pi/(J\tau)$")
    axes[0].legend(loc="best")
    finish_axes(axes[0])
    panel_label(axes[0], "(a)")

    axes[1].axhline(0.0, color=GRAY, linestyle=":", linewidth=1.2)
    axes[1].set_xlabel(r"$J\tau$")
    axes[1].set_ylabel(r"$\Delta_\tau S_R/(k_{\rm B}J\tau)$")
    axes[1].legend(loc="best")
    finish_axes(axes[1])
    panel_label(axes[1], "(b)")

    savefig(fig, "hardcore_local_defect_rate.pdf", w_pad=0.5)


def plot_local_defect_absolute_scaling(data: dict):
    """Supplementary log-log view of the absolute V_pi scaling at fixed t_ref."""
    colors = [RED, BLUE, GREEN]
    markers = ["o", "s", "^"]

    fig, ax = plt.subplots(figsize=(4.3, 3.0))
    for color, marker, case in zip(colors, markers, data["cases"]):
        rows = sorted(case["rows"], key=lambda r: r["tau"])
        tau = np.array([r["tau"] for r in rows], dtype=float)
        vpi = np.array([r["vpi"] for r in rows], dtype=float)
