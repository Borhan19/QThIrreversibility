# 2D hard-core lattice
# ============================================================


def square_lattice_edges(Lx: int, Ly: int):
    edges = []
    for y in range(Ly):
        for x in range(Lx):
            i = y * Lx + x
            if x + 1 < Lx:
                edges.append((i, y * Lx + (x + 1)))
            if y + 1 < Ly:
                edges.append((i, (y + 1) * Lx + x))
    return edges


def build_hardcore_2d_hamiltonian(
    Lx: int,
    Ly: int,
    Q: int,
    V: float,
    hopping: float = J,
):
    N = Lx * Ly
    basis, index = fixed_q_hardcore_basis(N, Q)
    edges = square_lattice_edges(Lx, Ly)
    rows, cols, vals = [], [], []

    for col, b in enumerate(basis):
        diag = 0.0
        for i, j in edges:
            diag += V * ((b >> i) & 1) * ((b >> j) & 1)
        rows.append(col)
        cols.append(col)
        vals.append(diag)

        for i, j in edges:
            ni = (b >> i) & 1
            nj = (b >> j) & 1
            if ni == nj:
                continue
            b2 = b ^ (1 << i) ^ (1 << j)
            rows.append(index[b2])
            cols.append(col)
            vals.append(-hopping)

    H = sp.csr_matrix(
        (vals, (rows, cols)), shape=(len(basis), len(basis)), dtype=np.complex128
    )
    return H, basis, index, edges


def quadrant_of_site(x: int, y: int, Lx: int, Ly: int):
    # Ordering keeps the two left quadrants first:
    # 0 = lower-left, 1 = upper-left, 2 = lower-right, 3 = upper-right.
    left = x < Lx // 2
    lower = y < Ly // 2
    if left and lower:
        return 0
    if left and not lower:
        return 1
    if not left and lower:
        return 2
    return 3


def hard_core_2d_macro_data(basis: list[int], Lx: int, Ly: int, Q: int):
    if Lx % 2 or Ly % 2:
        raise ValueError("Use even Lx and Ly for four equal quadrants.")
    cell_size = (Lx // 2) * (Ly // 2)

    labels = []

    def rec(prefix, remaining, cells_left):
        if cells_left == 1:
            if 0 <= remaining <= cell_size:
                labels.append(tuple(prefix + [remaining]))
            return
        for n in range(min(cell_size, remaining) + 1):
            rec(prefix + [n], remaining - n, cells_left - 1)

    rec([], Q, 4)
    labels = sorted(labels)
    label_to_id = {r: i for i, r in enumerate(labels)}

    site_quad = []
    for y in range(Ly):
        for x in range(Lx):
            site_quad.append(quadrant_of_site(x, y, Lx, Ly))

    macro_id = np.empty(len(basis), dtype=int)
    for ib, b in enumerate(basis):
        counts = [0, 0, 0, 0]
        for site in range(Lx * Ly):
            if (b >> site) & 1:
                counts[site_quad[site]] += 1
        macro_id[ib] = label_to_id[tuple(counts)]

    omega = np.array(
        [np.prod([math.comb(cell_size, n) for n in r]) for r in labels], dtype=float
    )
    pi = omega / np.sum(omega)

    group_counts = np.bincount(macro_id, minlength=len(labels))
    if not np.array_equal(group_counts, omega.astype(int)):
        raise RuntimeError("2D hard-core macro multiplicity mismatch.")

    return MacroData(labels=labels, macro_id=macro_id, omega=omega, pi=pi)


def hard_core_2d_left_half_initial_indices(
    basis: list[int], Lx: int, Ly: int, Q: int
):
    right_sites = []
    for y in range(Ly):
        for x in range(Lx // 2, Lx):
            right_sites.append(y * Lx + x)
    mask_right = sum(1 << j for j in right_sites)
    indices = [i for i, b in enumerate(basis) if (b & mask_right) == 0]
    expected = math.comb((Lx // 2) * Ly, Q)
    if len(indices) != expected:
        raise RuntimeError("Initial 2D hard-core class dimension mismatch.")
    return indices


