def main():
    hc_data = run_1d_hardcore() if RUN_1D_HARDCORE else None
    bh_data = run_bose_hubbard() if RUN_BOSE_HUBBARD else None
    d2_data = run_2d_hardcore() if RUN_2D_HARDCORE else None

    hc = hc_data["traj"] if hc_data else None
    bh = bh_data["traj"] if bh_data else None
    d2 = d2_data["traj"] if d2_data else None

    if hc is not None:
        print_trajectory_summary("1D interacting hard-core", hc)
    if bh is not None:
        print_trajectory_summary("1D Bose-Hubbard", bh)
    if d2 is not None:
        print_trajectory_summary("2D interacting hard-core", d2)

    if hc is not None and bh is not None and d2 is not None:
        plot_cross_model_generality(hc, bh, d2)
        plot_history_activity_generality(bh, d2)

    control = None
    if RUN_CONTROL_FAMILY:
        control = run_hardcore_control_family()
        plot_control_family(control)

    scan = None
    if RUN_PARAMETER_SCAN:
        scan = run_parameter_scan()
        plot_parameter_scan(scan)

    boundary = None
    if RUN_BOUNDARY_DT_REFINEMENT:
        boundary = run_boundary_dt_refinement()
        plot_boundary_dt_refinement(boundary)

    local_defect = None
    if RUN_LOCAL_DEFECT_RATE:
        local_defect = run_local_defect_rate_analysis()
        plot_local_defect_rate(local_defect)
        plot_local_defect_absolute_scaling(local_defect)

    stats = None
    if RUN_STATISTICS_LIMIT:
        stats = statistics_limit_data()
        plot_statistics_limit(stats)

    floquet = None
    if RUN_FLOQUET:
        def build_floquet():
            N = 12 if not QUICK_TEST else 8
            Q = 3 if not QUICK_TEST else 2
            periods = 30 if not QUICK_TEST else 8
            return analyze_floquet_class(
                N=N,
                Q=Q,
                Kcells=4,
                periods=periods,
                theta_even=0.63,
                theta_odd=0.83,
                phi=0.77,
            )

        floquet = cached("floquet_generality", build_floquet)
        plot_floquet(floquet)

    save_summary(
        hc=hc,
        bh=bh,
        d2=d2,
        control=control,
        scan=scan,
        floquet=floquet,
        boundary=boundary,
        local_defect=local_defect,
    )

    print("\nAll requested generality calculations are configured.")
    print(f"Figures: {FIG_DIR}")
    print(f"Data:    {DATA_DIR}")
    print(f"Cache:   {CACHE_DIR}")


if __name__ == "__main__":
    main()