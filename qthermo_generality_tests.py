def statistics_limit_data():
    # Genuine dilute thermodynamic sequence: Li=M^2, Q=M, Lf=2Li.
    M_values = np.arange(2, 41 if not QUICK_TEST else 10)
    rho = []
    hc_ratio = []
    boson_ratio = []

    for M in M_values:
        Li = int(M * M)
        Lf = 2 * Li
        Q = int(M)
        rho.append(Q / Li)

        dS_hc = log_binom(Lf, Q) - log_binom(Li, Q)
        dS_b = log_multichoose(Lf, Q) - log_multichoose(Li, Q)
        classical = Q * math.log(2.0)
        hc_ratio.append(dS_hc / classical)
        boson_ratio.append(dS_b / classical)

    # General volume ratio at a low fixed density sequence.
    lambdas = np.array([1.25, 1.5, 2.0, 3.0, 4.0])
    Q_general = 8
    Li_general = 400
    general_hc = []
    general_b = []
    for lam in lambdas:
        Lf = int(round(lam * Li_general))
        general_hc.append(
            (log_binom(Lf, Q_general) - log_binom(Li_general, Q_general)) / Q_general
        )
        general_b.append(
            (log_multichoose(Lf, Q_general) - log_multichoose(Li_general, Q_general)) / Q_general
        )

    return {
        "M": M_values,
        "rho": np.asarray(rho),
        "hc_ratio": np.asarray(hc_ratio),
        "boson_ratio": np.asarray(boson_ratio),
        "lambdas": lambdas,
        "ln_lambda": np.log(lambdas),
        "general_hc": np.asarray(general_hc),
        "general_boson": np.asarray(general_b),
    }


