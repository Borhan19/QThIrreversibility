    tau0 = float(rows0[0]["tau"])
    v0 = max(float(rows0[0]["vpi"]), 1e-18)
    guide_tau = np.array([tau0, max(r["tau"] for r in rows0)], dtype=float)
    guide_v = v0 * guide_tau / tau0
    ax.loglog(guide_tau, guide_v, color=BLACK, linestyle=":", linewidth=1.2, label=r"$\propto\tau$")

    ax.set_xlabel(r"$J\tau$")
    ax.set_ylabel(r"$\mathcal{V}_\pi$")
    ax.legend(loc="best")
    finish_axes(ax)
