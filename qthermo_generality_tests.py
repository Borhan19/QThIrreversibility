def weak_compositions(total: int, parts: int):
    if parts == 1:
        yield (total,)
        return
    for n in range(total + 1):
        for rest in weak_compositions(total - n, parts - 1):
            yield (n,) + rest


def fixed_q_boson_basis(L: int, Q: int):
    basis = list(weak_compositions(Q, L))
    return basis, {state: i for i, state in enumerate(basis)}


def build_bose_hubbard_hamiltonian(
    L: int,
    Q: int,
    U: float,
    hopping: float = J,
):
    basis, index = fixed_q_boson_basis(L, Q)
    rows, cols, vals = [], [], []

    for col, state in enumerate(basis):
        n = np.asarray(state, dtype=int)
        diag = 0.5 * U * float(np.sum(n * (n - 1)))
        rows.append(col)
        cols.append(col)
        vals.append(diag)

        for j in range(L - 1):
            # Move one boson from j+1 -> j.
            if n[j + 1] > 0:
                new = list(state)
                amp = -hopping * math.sqrt((n[j] + 1) * n[j + 1])
                new[j] += 1
                new[j + 1] -= 1
                rows.append(index[tuple(new)])
                cols.append(col)
                vals.append(amp)

            # Move one boson from j -> j+1.
            if n[j] > 0:
                new = list(state)
                amp = -hopping * math.sqrt((n[j + 1] + 1) * n[j])
                new[j] -= 1
                new[j + 1] += 1
                rows.append(index[tuple(new)])
                cols.append(col)
                vals.append(amp)

    H = sp.csr_matrix(
        (vals, (rows, cols)), shape=(len(basis), len(basis)), dtype=np.complex128
    )
    return H, basis, index


def boson_1d_macro_data(basis: list[tuple], L: int, Q: int, Kcells: int = 4):
    if L % Kcells != 0:
        raise ValueError("L must be divisible by Kcells.")
    ell = L // Kcells

    labels = sorted(set(weak_compositions(Q, Kcells)))
    label_to_id = {r: i for i, r in enumerate(labels)}

    macro_id = np.empty(len(basis), dtype=int)
    for ib, state in enumerate(basis):
        counts = []
        for a in range(Kcells):
            lo = a * ell
            hi = (a + 1) * ell
            counts.append(int(sum(state[lo:hi])))
        macro_id[ib] = label_to_id[tuple(counts)]

    omega = np.array(
        [
            np.prod([math.comb(ell + n - 1, n) for n in r])
            for r in labels
        ],
        dtype=float,
    )
    pi = omega / np.sum(omega)

    group_counts = np.bincount(macro_id, minlength=len(labels))
    if not np.array_equal(group_counts, omega.astype(int)):
        raise RuntimeError("Bosonic macro multiplicity mismatch.")

    return MacroData(labels=labels, macro_id=macro_id, omega=omega, pi=pi)


def boson_left_half_initial_indices(basis: list[tuple], L: int, Q: int):
    Li = L // 2
    indices = [i for i, state in enumerate(basis) if sum(state[Li:]) == 0]
    expected = math.comb(Li + Q - 1, Q)
    if len(indices) != expected:
        raise RuntimeError("Initial bosonic class dimension mismatch.")
    return indices


