def evaluate_parameter_point(N: int, Q: int, V1: float, V2: float, dt: float, tmax: float):
    H, basis, _ = build_hardcore_1d_hamiltonian(N, Q, V1, V2)
    macro = hard_core_1d_macro_data(basis, N, Q, Kcells=4)
    init = hard_core_left_half_initial_indices(basis, N, Q)
    times = np.arange(0.0, tmax + 0.5 * dt, dt)

    traj = analyze_time_independent_class(
        H,
        macro,
        init,
        times,
        tau=dt,
        compute_history_defect=False,
        metadata={"N": N, "Q": Q, "V1": V1, "V2": V2},
    )

    i10, i90 = traj.i10, traj.i90
    if i10 is None or i90 is None or i90 <= i10:
        return {
            "pass_fraction": np.nan,
            "max_vpi": np.nan,
            "min_rate": np.nan,
            "return_depth": np.nan,
            "t10": np.nan,
            "t90": np.nan,
        }

    # Pair indices corresponding to t in [t10,t90).
    pair_slice = slice(i10, i90)
    vv = traj.vpi[pair_slice]
    pass_fraction = float(np.mean(vv <= MAJ_TOL))
    max_vpi = float(np.max(vv))
    min_rate = float(np.min(traj.rate[i10 : i90 + 1]))

    return {
        "pass_fraction": pass_fraction,
        "max_vpi": max_vpi,
        "min_rate": min_rate,
        "return_depth": traj.metadata["return_depth"],
        "t10": float(traj.times[i10]),
        "t90": float(traj.times[i90]),
    }


