def fixed_q_hardcore_basis(N: int, Q: int):
    basis = []
    for occupied in itertools.combinations(range(N), Q):
        b = 0
        for j in occupied:
            b |= 1 << j
        basis.append(b)
    return basis, {b: i for i, b in enumerate(basis)}


def build_hardcore_1d_hamiltonian(
    N: int,
    Q: int,
    V1: float,
    V2: float,
    hopping: float = J,
):
    basis, index = fixed_q_hardcore_basis(N, Q)
    rows, cols, vals = [], [], []

    for col, b in enumerate(basis):
        diag = 0.0
        for j in range(N - 1):
            diag += V1 * ((b >> j) & 1) * ((b >> (j + 1)) & 1)
        for j in range(N - 2):
            diag += V2 * ((b >> j) & 1) * ((b >> (j + 2)) & 1)
        rows.append(col)
        cols.append(col)
        vals.append(diag)

        for j in range(N - 1):
            nj = (b >> j) & 1
            nk = (b >> (j + 1)) & 1
            if nj == nk:
                continue
            b2 = b ^ (1 << j) ^ (1 << (j + 1))
            rows.append(index[b2])
            cols.append(col)
            vals.append(-hopping)

    H = sp.csr_matrix(
        (vals, (rows, cols)), shape=(len(basis), len(basis)), dtype=np.complex128
    )
    return H, basis, index


def hard_core_1d_macro_data(basis: list[int], N: int, Q: int, Kcells: int = 4):
    if N % Kcells != 0:
        raise ValueError("N must be divisible by Kcells.")
    ell = N // Kcells

    labels = []

    def rec(prefix, remaining, cells_left):
        if cells_left == 1:
            if 0 <= remaining <= ell:
                labels.append(tuple(prefix + [remaining]))
            return
        for n in range(min(ell, remaining) + 1):
            rec(prefix + [n], remaining - n, cells_left - 1)

    rec([], Q, Kcells)
    labels = sorted(labels)
    label_to_id = {r: i for i, r in enumerate(labels)}

    macro_id = np.empty(len(basis), dtype=int)
    for ib, b in enumerate(basis):
        counts = []
        for a in range(Kcells):
            lo = a * ell
            hi = (a + 1) * ell
            count = sum((b >> j) & 1 for j in range(lo, hi))
            counts.append(count)
        macro_id[ib] = label_to_id[tuple(counts)]

    omega = np.array(
        [np.prod([math.comb(ell, n) for n in r]) for r in labels], dtype=float
    )
    pi = omega / np.sum(omega)

    # Exact consistency with the computational basis.
    group_counts = np.bincount(macro_id, minlength=len(labels))
    if not np.array_equal(group_counts, omega.astype(int)):
        raise RuntimeError("Hard-core macro multiplicity mismatch.")

    return MacroData(labels=labels, macro_id=macro_id, omega=omega, pi=pi)


def hard_core_left_half_initial_indices(basis: list[int], N: int, Q: int):
    Li = N // 2
    mask_right = sum(1 << j for j in range(Li, N))
    indices = [i for i, b in enumerate(basis) if (b & mask_right) == 0]
    expected = math.comb(Li, Q)
    if len(indices) != expected:
        raise RuntimeError("Initial hard-core class dimension mismatch.")
    return indices


def build_hardcore_1d_control_hamiltonian(N: int, Q: int, mode: str):
    """Uniform free hopping or matched-topology engineered mirror-return chain."""
    basis, index = fixed_q_hardcore_basis(N, Q)
    rows, cols, vals = [], [], []

    for col, b in enumerate(basis):
        rows.append(col)
        cols.append(col)
        vals.append(0.0)

        for j0 in range(N - 1):
            nj = (b >> j0) & 1
            nk = (b >> (j0 + 1)) & 1
            if nj == nk:
                continue

            if mode == "free":
                hop = -J
            elif mode == "engineered":
                j = j0 + 1
                hop = -(2.0 * J / N) * math.sqrt(j * (N - j))
            else:
                raise ValueError("mode must be 'free' or 'engineered'.")

            b2 = b ^ (1 << j0) ^ (1 << (j0 + 1))
            rows.append(index[b2])
            cols.append(col)
            vals.append(hop)

    H = sp.csr_matrix(
        (vals, (rows, cols)), shape=(len(basis), len(basis)), dtype=np.complex128
    )
    return H, basis, index


