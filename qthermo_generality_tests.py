"""
Generality tests for the closed-system thermodynamic irreversibility framework.

The script is deliberately modular. It tests the same thermodynamic construction in
several microscopically distinct closed quantum systems:

1. 1D interacting hard-core chain (baseline model).
2. 1D interacting Bose-Hubbard chain (different statistics and local Hilbert space).
3. 2D interacting hard-core lattice (different spatial geometry).
4. A broad (V1,V2) scan of the 1D hard-core model (fine-tuning test).
5. A number-conserving Floquet circuit (optional, demonstrates that a static
   Hamiltonian is not required by the theorem).
6. Exact hard-core versus bosonic free-expansion counting in the dilute limit.
7. Time-step refinement of the strong-coupling V1/J=2 boundary.
8. Fixed-time finite-step relative-majorization defect-rate scaling.

All microscopic realizations use one closed system. For a fixed Hamiltonian/unitary
and a fixed fine initial microstate there is one unique microscopic history. The
thermodynamic preparation specifies only a macrostate, so the compatible history
class is generated by the different fine initial microstates consistent with that
same preparation.

All entropy values are reported in units of k_B unless stated otherwise.
"""

