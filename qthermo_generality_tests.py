def build_hardcore_layer_hamiltonian(
    N: int,
    Q: int,
    bond_parity: int,
    hopping: float = J,
):
    basis, index = fixed_q_hardcore_basis(N, Q)
    rows, cols, vals = [], [], []
    for col, b in enumerate(basis):
        rows.append(col)
        cols.append(col)
        vals.append(0.0)
        for j in range(bond_parity, N - 1, 2):
            nj = (b >> j) & 1
            nk = (b >> (j + 1)) & 1
            if nj == nk:
                continue
            b2 = b ^ (1 << j) ^ (1 << (j + 1))
            rows.append(index[b2])
            cols.append(col)
            vals.append(-hopping)
    H = sp.csr_matrix(
        (vals, (rows, cols)), shape=(len(basis), len(basis)), dtype=np.complex128
    )
    return H, basis, index


def build_hardcore_interaction_diagonal(N: int, Q: int):
    basis, _ = fixed_q_hardcore_basis(N, Q)
    diag = np.zeros(len(basis), dtype=float)
    for i, b in enumerate(basis):
        diag[i] = sum(
            ((b >> j) & 1) * ((b >> (j + 1)) & 1) for j in range(N - 1)
        )
    return diag, basis


def floquet_action_factory(N: int, Q: int, theta_even: float, theta_odd: float, phi: float):
    H_even, basis, _ = build_hardcore_layer_hamiltonian(N, Q, bond_parity=0)
    H_odd, _, _ = build_hardcore_layer_hamiltonian(N, Q, bond_parity=1)
    diag_int, _ = build_hardcore_interaction_diagonal(N, Q)
    phase = np.exp(-1j * phi * diag_int)

    def action(X: np.ndarray):
        Y = expm_multiply(-1j * theta_even * H_even, X)
        Y = expm_multiply(-1j * theta_odd * H_odd, Y)
        Y = phase[:, None] * Y if Y.ndim == 2 else phase * Y
        return Y

    return action, basis


def analyze_floquet_class(
    N: int,
    Q: int,
    Kcells: int,
    periods: int,
    theta_even: float,
    theta_odd: float,
    phi: float,
):
    action, basis = floquet_action_factory(N, Q, theta_even, theta_odd, phi)
    macro = hard_core_1d_macro_data(basis, N, Q, Kcells)
    initial_indices = hard_core_left_half_initial_indices(basis, N, Q)

    dim = len(basis)
    psi = basis_columns(dim, initial_indices)
    p = np.zeros((periods + 1, len(macro.omega)), dtype=float)
    entropy = np.zeros(periods + 1, dtype=float)

    p[0] = macro_probabilities_from_columns(psi, macro)
    entropy[0] = coarse_entropy(p[0], macro.omega)

    for n in range(periods):
        psi = action(psi)
        p[n + 1] = macro_probabilities_from_columns(psi, macro)
        entropy[n + 1] = coarse_entropy(p[n + 1], macro.omega)

    S0 = entropy[0]
    Smax = math.log(float(np.sum(macro.omega)))
    sigma = (entropy - S0) / (Smax - S0)

    K = build_coarse_K_from_step(dim, macro, action)
    stoch_err, pi_err, min_entry = verify_K(K, macro.pi)
    print(
        "Floquet K checks:",
        f"stochasticity={stoch_err:.3e},",
        f"pi-preservation={pi_err:.3e},",
        f"min entry={min_entry:.3e}",
    )

    vpi = np.zeros(periods, dtype=float)
    eps = np.zeros(periods, dtype=float)
    ds_mix = np.zeros(periods, dtype=float)
    ds_corr = np.zeros(periods, dtype=float)

    for n in range(periods):
        vpi[n] = majorization_defect(p[n], p[n + 1], macro.pi)
        q0 = safe_normalize(K @ p[n])
        r = p[n + 1] - q0
        eps[n] = 0.5 * np.sum(np.abs(r))
        ds_mix[n] = coarse_entropy(q0, macro.omega) - coarse_entropy(p[n], macro.omega)
        ds_corr[n] = coarse_entropy(p[n + 1], macro.omega) - coarse_entropy(q0, macro.omega)

    i10, i90 = primary_window_indices(sigma)
    return {
        "periods": np.arange(periods + 1),
        "p": p,
        "entropy": entropy,
        "sigma": sigma,
        "vpi": vpi,
        "epsilon_hist": eps,
        "ds_mix": ds_mix,
        "ds_corr": ds_corr,
        "i10": i10,
        "i90": i90,
        "dim": dim,
        "initial_class_dim": len(initial_indices),
        "parameters": (theta_even, theta_odd, phi),
    }


