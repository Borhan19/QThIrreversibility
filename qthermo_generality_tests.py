def cached(name: str, builder: Callable[[], dict]):
    path = CACHE_DIR / f"{name}.pkl"
    if path.exists() and not FORCE_RECOMPUTE:
        print(f"Loading cache: {path}")
        with path.open("rb") as f:
            return pickle.load(f)

    print(f"Computing: {name}")
    data = builder()
    with path.open("wb") as f:
        pickle.dump(data, f, protocol=pickle.HIGHEST_PROTOCOL)
    print(f"Cached: {path}")
    return data


def log_binom(n: int, k: int) -> float:
    if k < 0 or k > n:
        return -np.inf
    return float(gammaln(n + 1) - gammaln(k + 1) - gammaln(n - k + 1))


def log_multichoose(L: int, Q: int) -> float:
    """log number of weak compositions of Q bosons among L sites."""
    if L <= 0 or Q < 0:
        return -np.inf
    return log_binom(L + Q - 1, Q)


def safe_normalize(p: np.ndarray) -> np.ndarray:
    p = np.asarray(p, dtype=float).copy()
    p[np.abs(p) < PROB_TOL] = 0.0
    p[p < 0.0] = 0.0
    s = p.sum()
    if s <= 0.0:
        raise ValueError("Probability vector has non-positive normalization.")
    return p / s


def coarse_entropy(p: np.ndarray, omega: np.ndarray) -> float:
    """S_R/k_B = -sum_R p_R log(p_R/Omega_R)."""
    p = safe_normalize(p)
    omega = np.asarray(omega, dtype=float)
    mask = p > 0.0
    return float(-np.sum(p[mask] * np.log(p[mask] / omega[mask])))


def relative_entropy(p: np.ndarray, pi: np.ndarray) -> float:
    p = safe_normalize(p)
    pi = safe_normalize(pi)
    mask = p > 0.0
    return float(np.sum(p[mask] * np.log(p[mask] / pi[mask])))


def generalized_lorenz_points(p: np.ndarray, pi: np.ndarray):
    """Return generalized Lorenz curve breakpoints (x,y)."""
    p = safe_normalize(p)
    pi = safe_normalize(pi)
    if np.any(pi <= 0.0):
        raise ValueError("pi must have full support on the included macrostates.")

    order = np.argsort(-(p / pi), kind="mergesort")
    xs = np.concatenate([[0.0], np.cumsum(pi[order])])
    ys = np.concatenate([[0.0], np.cumsum(p[order])])
    xs[-1] = 1.0
    ys[-1] = 1.0
    return xs, ys


def lorenz_value(xs: np.ndarray, ys: np.ndarray, x: np.ndarray) -> np.ndarray:
    return np.interp(x, xs, ys)


def majorization_defect(p: np.ndarray, q: np.ndarray, pi: np.ndarray) -> float:
    """
    V_pi(p -> q) = sup_x [L_q^pi(x)-L_p^pi(x)]_+.

    Since both curves are piecewise linear, it is sufficient to evaluate the
    difference at the union of their breakpoints.
    """
    xp, yp = generalized_lorenz_points(p, pi)
    xq, yq = generalized_lorenz_points(q, pi)
    x = np.unique(np.concatenate([xp, xq]))
    diff = lorenz_value(xq, yq, x) - lorenz_value(xp, yp, x)
    return float(max(0.0, np.max(diff)))


def lorenz_margin(p: np.ndarray, q: np.ndarray, pi: np.ndarray) -> float:
    """Minimum L_p-L_q over all generalized-Lorenz breakpoints."""
    xp, yp = generalized_lorenz_points(p, pi)
    xq, yq = generalized_lorenz_points(q, pi)
    x = np.unique(np.concatenate([xp, xq]))
    diff = lorenz_value(xp, yp, x) - lorenz_value(xq, yq, x)
    return float(np.min(diff))


def group_sum(values: np.ndarray, macro_id: np.ndarray, n_macro: int) -> np.ndarray:
    return np.bincount(macro_id, weights=np.asarray(values, dtype=float), minlength=n_macro)


def first_crossing(y: np.ndarray, level: float, start: int = 0):
    idx = np.where(np.asarray(y)[start:] >= level)[0]
    if len(idx) == 0:
        return None
    return int(start + idx[0])


def primary_window_indices(sigma: np.ndarray):
    i10 = first_crossing(sigma, 0.10)
    if i10 is None:
        return None, None
    i90 = first_crossing(sigma, 0.90, start=i10)
    return i10, i90


def entropy_return_depth(sigma: np.ndarray, i90: int | None) -> float:
    if i90 is None or i90 >= len(sigma) - 1:
        return np.nan
    running_max = -np.inf
    max_drop = 0.0
    for value in sigma[i90:]:
        running_max = max(running_max, value)
        max_drop = max(max_drop, running_max - value)
    return float(max_drop)


@dataclass
class MacroData:
    labels: list[tuple]
    macro_id: np.ndarray
    omega: np.ndarray
    pi: np.ndarray


@dataclass
class Trajectory:
    times: np.ndarray
    p: np.ndarray
    entropy: np.ndarray
    sigma: np.ndarray
    rate: np.ndarray | None
    vpi: np.ndarray
    margin: np.ndarray
    epsilon_hist: np.ndarray | None
    ds_mix: np.ndarray | None
    ds_corr: np.ndarray | None
    i10: int | None
    i90: int | None
    metadata: dict


# ============================================================
# Generic class-level trajectory calculation
# ============================================================


def basis_columns(dim: int, indices: Iterable[int]) -> np.ndarray:
    idx = np.asarray(list(indices), dtype=int)
    psi0 = np.zeros((dim, len(idx)), dtype=np.complex128)
    psi0[idx, np.arange(len(idx))] = 1.0
    return psi0


def macro_probabilities_from_columns(psi: np.ndarray, macro: MacroData) -> np.ndarray:
    # psi shape = (dim, n_columns); equal-weight thermodynamic class.
    site_prob = np.mean(np.abs(psi) ** 2, axis=1)
    return safe_normalize(group_sum(site_prob, macro.macro_id, len(macro.omega)))


def macro_rate_from_columns(
    psi: np.ndarray,
    H: sp.spmatrix,
    macro: MacroData,
) -> np.ndarray:
    dpsi = -1j * (H @ psi)
    dsite = np.mean(2.0 * np.real(np.conj(psi) * dpsi), axis=1)
    return group_sum(dsite, macro.macro_id, len(macro.omega))


def entropy_rate_from_dp(p: np.ndarray, dp: np.ndarray, omega: np.ndarray) -> float:
    p = safe_normalize(p)
    mask = p > 1e-15
    # The normalization term vanishes because sum dp = 0.
    return float(-np.sum(dp[mask] * np.log(p[mask] / omega[mask])))


def build_coarse_K_from_step(
    dim: int,
    macro: MacroData,
    step_action: Callable[[np.ndarray], np.ndarray],
) -> np.ndarray:
    """
    Construct the exact macro-uniform K^(U) for one finite unitary step.

    K_RR' is obtained by uniformly averaging over all microscopic basis states
    belonging to initial macrospace R'. This is practical for the representative
    systems used here (dimensions O(10^2)-O(10^3)).
    """
    eye = np.eye(dim, dtype=np.complex128)
    Ucols = step_action(eye)
    n_macro = len(macro.omega)

    # T[R, j] = probability to end in macro R from microscopic basis state j.
    T = np.zeros((n_macro, dim), dtype=float)
    abs2 = np.abs(Ucols) ** 2
    for j in range(dim):
        T[:, j] = group_sum(abs2[:, j], macro.macro_id, n_macro)

    K = np.zeros((n_macro, n_macro), dtype=float)
    for rp in range(n_macro):
        cols = np.where(macro.macro_id == rp)[0]
        if len(cols) != int(round(macro.omega[rp])):
            raise RuntimeError("Macrospace dimension does not match basis grouping.")
        K[:, rp] = np.mean(T[:, cols], axis=1)

    # Small numerical cleanup.
    K[np.abs(K) < 1e-15] = 0.0
    return K


def verify_K(K: np.ndarray, pi: np.ndarray):
    stoch_err = float(np.max(np.abs(np.sum(K, axis=0) - 1.0)))
    pi_err = float(np.max(np.abs(K @ pi - pi)))
    min_entry = float(np.min(K))
    return stoch_err, pi_err, min_entry


def analyze_time_independent_class(
    H: sp.spmatrix,
    macro: MacroData,
    initial_indices: list[int],
    times: np.ndarray,
    tau: float,
    compute_history_defect: bool = True,
    metadata: dict | None = None,
) -> Trajectory:
    dim = H.shape[0]
    psi0 = basis_columns(dim, initial_indices)

    # expm_multiply returns shape (nt, dim, n_initial) for matrix B.
    states = expm_multiply(
        -1j * H,
        psi0,
        start=float(times[0]),
        stop=float(times[-1]),
        num=len(times),
        endpoint=True,
    )

    nt = len(times)
    n_macro = len(macro.omega)
    p = np.zeros((nt, n_macro), dtype=float)
    entropy = np.zeros(nt, dtype=float)
    rate = np.zeros(nt, dtype=float)

    for it in range(nt):
        p[it] = macro_probabilities_from_columns(states[it], macro)
        entropy[it] = coarse_entropy(p[it], macro.omega)
        dp = macro_rate_from_columns(states[it], H, macro)
        rate[it] = entropy_rate_from_dp(p[it], dp, macro.omega)

    S0 = entropy[0]
    Smax = math.log(float(np.sum(macro.omega)))
    denom = Smax - S0
    sigma = (entropy - S0) / denom if denom > 0 else np.zeros_like(entropy)

    vpi = np.full(nt - 1, np.nan)
    margin = np.full(nt - 1, np.nan)
    for it in range(nt - 1):
        vpi[it] = majorization_defect(p[it], p[it + 1], macro.pi)
        margin[it] = lorenz_margin(p[it], p[it + 1], macro.pi)

    epsilon_hist = None
    ds_mix = None
    ds_corr = None

    dt = float(times[1] - times[0])
    if compute_history_defect:
        if abs(dt - tau) > 1e-10:
            raise ValueError("For history-defect calculation, grid spacing must equal tau.")

        step_action = lambda X: expm_multiply(-1j * H * tau, X)
        K = build_coarse_K_from_step(dim, macro, step_action)
        stoch_err, pi_err, min_entry = verify_K(K, macro.pi)
        print(
            "K checks:",
            f"stochasticity={stoch_err:.3e},",
            f"pi-preservation={pi_err:.3e},",
            f"min entry={min_entry:.3e}",
        )

        epsilon_hist = np.zeros(nt - 1, dtype=float)
        ds_mix = np.zeros(nt - 1, dtype=float)
        ds_corr = np.zeros(nt - 1, dtype=float)

        for it in range(nt - 1):
            q0 = safe_normalize(K @ p[it])
            q = p[it + 1]
            r = q - q0
            epsilon_hist[it] = 0.5 * np.sum(np.abs(r))
            ds_mix[it] = coarse_entropy(q0, macro.omega) - coarse_entropy(p[it], macro.omega)
            ds_corr[it] = coarse_entropy(q, macro.omega) - coarse_entropy(q0, macro.omega)

            # Exact numerical bound check.
            if vpi[it] - epsilon_hist[it] > 5e-10:
                raise RuntimeError("Numerical violation of V_pi <= epsilon_hist.")

    i10, i90 = primary_window_indices(sigma)

    md = dict(metadata or {})
    md.update(
        {
            "dim": dim,
            "initial_class_dim": len(initial_indices),
            "S0": S0,
            "Smax": Smax,
            "return_depth": entropy_return_depth(sigma, i90),
        }
    )

    return Trajectory(
        times=times,
        p=p,
        entropy=entropy,
        sigma=sigma,
        rate=rate,
        vpi=vpi,
        margin=margin,
        epsilon_hist=epsilon_hist,
        ds_mix=ds_mix,
        ds_corr=ds_corr,
        i10=i10,
        i90=i90,
        metadata=md,
    )


