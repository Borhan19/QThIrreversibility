def save_summary(hc=None, bh=None, d2=None, control=None, scan=None, floquet=None, boundary=None, local_defect=None):
    lines = []
    lines.append("Generality tests for closed-system thermodynamic irreversibility\n")
    lines.append("All entropies are in units of k_B.\n")

    def add_traj(name, traj: Trajectory):
        lines.append(f"\n{name}\n")
        lines.append("-" * len(name) + "\n")
        lines.append(f"metadata = {traj.metadata}\n")
        if traj.i10 is not None and traj.i90 is not None:
            lines.append(
                f"primary window = {traj.times[traj.i10]:.8g} -> {traj.times[traj.i90]:.8g}\n"
            )
            lines.append(
                f"min primary rate = {np.min(traj.rate[traj.i10:traj.i90+1]):.12g}\n"
            )
            lines.append(
                f"max primary V_pi = {np.max(traj.vpi[traj.i10:traj.i90]):.12g}\n"
            )
            lines.append(
                f"majorization pass fraction = {np.mean(traj.vpi[traj.i10:traj.i90] <= MAJ_TOL):.12g}\n"
            )
            if traj.epsilon_hist is not None:
                lines.append(
                    f"max primary epsilon_hist = {np.max(traj.epsilon_hist[traj.i10:traj.i90]):.12g}\n"
                )
        lines.append(f"max Sigma = {np.max(traj.sigma):.12g}\n")
        lines.append(f"post-relaxation return depth = {traj.metadata.get('return_depth')}\n")

    if hc is not None:
        add_traj("1D interacting hard-core", hc)
    if bh is not None:
        add_traj("1D Bose-Hubbard", bh)
    if d2 is not None:
        add_traj("2D interacting hard-core", d2)

    if control is not None:
        lines.append("\nHard-core control family\n")
        lines.append("------------------------\n")
        lines.append(f"mirror time = {control['mirror_time']:.12g}\n")
        for key in ("mixing", "free", "engineered"):
            traj = control[key]
            lines.append(f"{key}: max Sigma = {np.max(traj.sigma):.12g}, max V_pi = {np.max(traj.vpi):.12g}\n")

    if scan is not None:
        valid = np.isfinite(scan["pass_fraction"])
        lines.append("\nHard-core parameter scan\n")
        lines.append("------------------------\n")
        lines.append(f"N={scan['N']}, Q={scan['Q']}, dt={scan['dt']}, tmax={scan['tmax']}\n")
        if np.any(valid):
            lines.append(
                f"fraction of valid grid points with pass fraction 1 = {np.mean(scan['pass_fraction'][valid] >= 1.0 - 1e-12):.12g}\n"
            )
            lines.append(
                f"median pass fraction = {np.nanmedian(scan['pass_fraction']):.12g}\n"
            )
            lines.append(
                f"maximum primary V_pi over grid = {np.nanmax(scan['max_vpi']):.12g}\n"
            )
            lines.append(
                f"minimum primary entropy rate over grid = {np.nanmin(scan['min_rate']):.12g}\n"
            )

    if floquet is not None:
        lines.append("\nFloquet test\n")
        lines.append("------------\n")
        lines.append(f"dim = {floquet['dim']}\n")
        lines.append(f"initial class dim = {floquet['initial_class_dim']}\n")
        lines.append(f"parameters = {floquet['parameters']}\n")
        if floquet["i10"] is not None and floquet["i90"] is not None:
            sl = slice(floquet["i10"], floquet["i90"])
            lines.append(f"max primary V_pi = {np.max(floquet['vpi'][sl]):.12g}\n")
            lines.append(f"max primary epsilon_hist = {np.max(floquet['epsilon_hist'][sl]):.12g}\n")

    if boundary is not None:
        lines.append("\nStrong-coupling boundary time-step refinement\n")
        lines.append("---------------------------------------------\n")
        lines.append(
            f"N={boundary['N']}, Q={boundary['Q']}, V1/J={boundary['V1']}, "
            f"tmax={boundary['tmax']}\n"
        )
        for dt in boundary["dt_values"]:
            subset = [r for r in boundary["rows"] if np.isclose(r["dt"], dt)]
            lines.append(
                f"dt={dt:.8g}: min pass fraction={np.nanmin([r['pass_fraction'] for r in subset]):.12g}, "
                f"max V_pi={np.nanmax([r['max_vpi'] for r in subset]):.12g}, "
                f"min entropy rate={np.nanmin([r['min_rate'] for r in subset]):.12g}\n"
            )

    if local_defect is not None:
        lines.append("\nFixed-time local relative-majorization defect-rate refinement\n")
        lines.append("---------------------------------------------------------\n")
        for case in local_defect["cases"]:
            lines.append(
                f"V1/J={case['V1']}, V2/J={case['V2']}, t_ref={case['t_ref']:.12g}, "
                f"instantaneous entropy rate={case['instantaneous_entropy_rate']:.12g}\n"
            )
            for row in sorted(case["rows"], key=lambda r: r["tau"], reverse=True):
                lines.append(
                    f"  tau={row['tau']:.12g}, V_pi={row['vpi']:.12g}, "
                    f"V_pi/tau={row['nu_pi']:.12g}, DeltaS/tau={row['finite_entropy_rate']:.12g}\n"
                )

    path = DATA_DIR / "generality_summary.txt"
    path.write_text("".join(lines), encoding="utf-8")
    print(f"Saved: {path}")

    if scan is not None:
        csv_path = DATA_DIR / "hardcore_parameter_scan.csv"
        with csv_path.open("w", encoding="utf-8") as f:
            f.write("V1_over_J,V2_over_J,pass_fraction,max_Vpi,min_rate,return_depth,t10,t90\n")
            for iy, V2 in enumerate(scan["V2_values"]):
                for ix, V1 in enumerate(scan["V1_values"]):
                    f.write(
                        f"{V1},{V2},{scan['pass_fraction'][iy,ix]},{scan['max_vpi'][iy,ix]},"
                        f"{scan['min_rate'][iy,ix]},{scan['return_depth'][iy,ix]},"
                        f"{scan['t10'][iy,ix]},{scan['t90'][iy,ix]}\n"
                    )
        print(f"Saved: {csv_path}")


